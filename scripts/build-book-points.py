def lecture_of(ref):
    if not ref:
        return None
    num = ref.split(".")[0].split("/")[0]
    return int(num) if num.isdigit() else None

found = {}
def walk(node, lec=None):
    if not isinstance(node, dict):
        return
    ref = node.get("ref") or ""
    my = lecture_of(ref) or lec
    kids = node.get("children") or []
    title = node.get("title") or ""
    if title in SKIP:
        for child in kids:
            walk(child, my)
        return
    take = (kids and all(not (c.get("children") or []) for c in kids)) or (not kids and title)
    if take and ref in SAY:
        name, say = SAY[ref]
        found.setdefault(my, []).append({
            "ref": ref,
            "name": name,
            "book": title,
            "say": say,
            "songs": SONGS.get(ref, []),
        })
        return
    if take and ref:
        print("MISSING", ref, title)
        return
    for child in kids:
        walk(child, my)
